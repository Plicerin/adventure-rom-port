/**
 * Decode one 3-byte PF0/PF1/PF2 row into a 20-bit pattern. PF0 is the
 * 4 high bits of the rightmost 4 pixels, PF1 is the middle 8 bits,
 * PF2 is the leftmost 8 pixels (reflected for mirrored mode).
 */
export function decodePlayfieldRow(pf0, pf1, pf2) {
  return {
    pf0, pf1, pf2,
    // High 4 bits of right half
    right4: pf0,
    // 8 bits of middle
    middle8: pf1,
    // 8 bits of left half
    left8: pf2,
  };
}

