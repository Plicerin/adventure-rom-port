/**
 * Sprite atlas for the Adventure port.
 *
 * Each sprite is a list of bytes from the actual adventure.asm graphics
 * tables (e.g. GfxChallise, GfxMagnet, GfxSword, GfxKey, GfxDrag0/1/2,
 * GfxBat1/2, GfxNum1/2/3, GfxAuthor, GfxDot, GfxSurround). The original
 * Atari 2600 stored graphics as 1 byte per scanline (vertical), where
 * each byte is a column of 8 vertical pixels. We preserve that format
 * here so the visuals match the source-of-truth ASM data.
 *
 * The render path (`renderSpriteToCanvas`) draws each byte as one
 * column of 8 pixels, producing an 8-wide × N-tall sprite. Sprites
 * are pre-rendered to offscreen canvases at native size on first
 * request and cached.
 *
 * The 30 room wall patterns (PF0/PF1/PF2 triples) are stored in
 * ROOM_WALLS in the same vertical format - each row is 3 bytes that
 * form a 20-bit playfield pattern, mirrored to fill the 160-pixel
 * screen width. The renderer paints them as solid horizontal bands.
 */

