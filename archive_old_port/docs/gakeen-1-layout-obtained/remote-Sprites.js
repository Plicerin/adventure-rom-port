function renderSpriteToCanvas(bytes, color) {
    const w = 8;
    const h = bytes.length;
    const canvas = document.createElement('canvas');
    canvas.width = w;
    canvas.height = h;
    const ctx = canvas.getContext('2d');
    ctx.fillStyle = color;
    for (let col = 0; col < bytes.length; col++) {
        const b = bytes[col];
        for (let bit = 0; bit < 8; bit++) {
            // Atari TIA bit ordering: high bit = topmost pixel
            if (b & (0x80 >> bit)) {
                ctx.fillRect(col, bit, 1, 1);
            }
        }
    }
    return canvas;
}

const spriteCache = {};

/**
 * Returns a pre-rendered HTMLCanvasElement for the given sprite id and
 * color, or null if unknown. Sprites are 8 pixels wide and N pixels
 * tall (where N = number of bytes in the source graphic).
 */
export function getSprite(id, color) {
  const cacheKey = `${id}_${color}`;
  if (spriteCache[cacheKey]) return spriteCache[cacheKey];
  const bytes = SPRITE_DEFS[id];
  if (!bytes) return null;
  spriteCache[cacheKey] = renderSpriteToCanvas(bytes, color);
  return spriteCache[cacheKey];
}

